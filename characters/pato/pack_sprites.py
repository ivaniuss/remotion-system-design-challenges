"""Packs the rendered frames into .webp sprite sheets and writes the manifest.

Usage: python3 pack_sprites.py <remotion project folder>
Writes public/host/pato/<clip>.<variant>.webp and src/host/pato.ts in that project.
"""
import json, os, sys
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
FRAMES = os.path.join(HERE, "frames")
COLS = 8


def main():
    project = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "..", "..")  # the project root
    meta = json.load(open(os.path.join(FRAMES, "clips.json")))
    size = meta["size"]
    out_dir = os.path.join(project, "public", "host", "pato")
    os.makedirs(out_dir, exist_ok=True)
    clips = {}
    for name, c in meta["clips"].items():
        variants = ["closed", "half", "open"] if c["talks"] else ["main"]
        sheets = {}
        for var in variants:
            d = os.path.join(FRAMES, name, var)
            files = [os.path.join(d, f"{i:03d}.png") for i in range(c["frames"])]
            missing = [f for f in files if not os.path.exists(f)]
            if missing:
                sys.exit(f"{len(missing)} frames missing in {d}: render them first (animate_pato.py)")
            rows = (len(files) + COLS - 1) // COLS
            sheet = Image.new("RGBA", (COLS * size, rows * size), (0, 0, 0, 0))
            for i, f in enumerate(files):
                im = Image.open(f).convert("RGBA")
                r, g, b, a = im.split()
                a = a.point(lambda v: 0 if v < 8 else v)   # drop the noise of the invisible floor
                im = Image.merge("RGBA", (r, g, b, a))
                sheet.paste(im, ((i % COLS) * size, (i // COLS) * size))
            rel = f"host/pato/{name}.{var}.webp"
            sheet.save(os.path.join(project, "public", rel), "WEBP", quality=88, method=6)
            sheets[var] = rel
            print(f"{rel}: {len(files)} frames, {os.path.getsize(os.path.join(project, 'public', rel)) // 1024} KB")
        clips[name] = {"frames": c["frames"], "intro": c["intro"], "outro": c["outro"], "talks": c["talks"], "sheets": sheets}

    manifest = {"fps": meta["fps"], "size": size, "cols": COLS, "clips": clips}
    ts = os.path.join(project, "src", "host", "pato.ts")
    os.makedirs(os.path.dirname(ts), exist_ok=True)
    with open(ts, "w") as f:
        f.write("// Generated by characters/pato/pack_sprites.py from the Blender renders. Do not edit.\n")
        f.write("// Each clip is a sprite sheet (cols × rows of size×size frames, transparent background).\n")
        f.write("// intro/outro: frames that go from / back to the neutral pose; the rest loops.\n")
        f.write("import type {HostManifest} from './types';\n\n")
        f.write("export const PATO: HostManifest = " + json.dumps(manifest, indent=2) + ";\n")
    print("manifest:", ts)


if __name__ == "__main__":
    main()
